const path = require("path");
const HtmlWebpackPlugin = require("html-webpack-plugin");

module.exports = {
  // Set the mode to 'development' or 'production'
  mode: "development",

  // The entry point for Webpack. This is the main JS file that Webpack will start bundling from.
  // We point it to the output of our tsc compilation.
  entry: "./dist/index.js",

  // The output configuration tells Webpack where to put the bundled file(s).
  output: {
    filename: "bundle.js", // The name of your final bundled JavaScript file.
    path: path.resolve(__dirname, "../public"), // The directory where the bundle will be saved.
    clean: false, // Cleans the 'build' directory before each build.
  },

  // Loaders tell Webpack how to process different file types.
  // Since we've already compiled TS to JS with tsc, we don't need ts-loader here.
  // We'll focus on processing the JS files from 'dist'.
  module: {
    rules: [
      // You might add rules for CSS, images, etc. here if needed.
      // For example, if you have CSS files:
      // {
      //   test: /\.css$/,
      //   use: ['style-loader', 'css-loader'],
      // },
    ],
  },

  // Plugins enhance Webpack's capabilities.
  plugins: [
    new HtmlWebpackPlugin({
      template: "./public/index.html", // Path to your original HTML template.
      filename: "index.html", // The name of the output HTML file.
      inject: "head", // Injects the bundle script into the <body>.
      minify: false,
      hash: true,
      scriptLoading: "blocking",
      
    }),
  ],

  // Development server configuration for live reloading.
  devServer: {
    static: "./build", // Serve files from the 'build' directory.
    hot: true, // Enable Hot Module Replacement.
    open: true, // Automatically open the browser when the server starts.
    compress: true, // Enable gzip compression.
  },

  // Source maps configuration to link bundled code back to original TS.
  // Webpack will use the source maps generated by tsc.
  devtool: "source-map",
};
